// Build the D1 seed (SQL) from the app's library file.
//   node scripts/build_seed.mjs seed/data.json seed/seed.sql
// Tokens, document frequencies and passage lengths are computed with the same tokenizer and text the browser app
// used ("title | heading | text"), so the Worker's search returns the same passages in the same order.
import fs from "node:fs";

const [src, out] = process.argv.slice(2);
const data = JSON.parse(fs.readFileSync(src, "utf8"));
const tok = (s) => s.toLowerCase().match(/[a-z0-9]+(?:[.%][0-9]+)?/g) || [];
const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => (v === undefined || v === null ? "NULL" : q(JSON.stringify(v)));

const lines = ["-- generated by scripts/build_seed.mjs; do not edit",
  "DELETE FROM chunk_terms; DELETE FROM scope_df; DELETE FROM scopes; DELETE FROM chunks; DELETE FROM pages; DELETE FROM manuals;"];
const MAX = 90_000;   // D1 limits one SQL statement to 100 KB
const insert = (table, cols, rows) => {
  let buf = [], size = 0;
  const flush = () => { if (buf.length) lines.push(`INSERT INTO ${table} (${cols}) VALUES ${buf.join(",")};`); buf = []; size = 0; };
  for (const r of rows) { const v = `(${r.join(",")})`; if (size + v.length > MAX) flush(); buf.push(v); size += v.length + 1; }
  flush();
};

const manualRows = [], pageRows = [], chunkRows = [], termRows = [];
const scopeDf = new Map(), scopes = new Map();
const bump = (scope, terms, len) => {
  if (!scopeDf.has(scope)) { scopeDf.set(scope, new Map()); scopes.set(scope, { n: 0, total: 0 }); }
  const df = scopeDf.get(scope), s = scopes.get(scope);
  for (const t of terms) df.set(t, (df.get(t) || 0) + 1);
  s.n += 1; s.total += len;
};
let chunkId = 0;
data.manuals.forEach((m, ord) => {
  manualRows.push([q(m.id), ord, q(m.corpus), q(m.title), q(m.maker || null), q(m.equipment || null), q(m.trust || null), q(m.source || null),
    json(m.pages), q(m.total_pages ?? m.pages.length), q(m.pdf ? `files/${m.pdf}` : null), json(m.figs || null), json(m.examples || []),
    q(m.parser || data.parser || null), json(m.security || null), q(m.added_at || null)]);
  for (const [p, text] of Object.entries(m.page_text || {})) pageRows.push([q(m.id), Number(p), q(text)]);
  for (const c of m.chunks) {
    chunkId += 1;
    const toks = tok(`${m.title} | ${c.heading} | ${c.text}`), tf = new Map();
    for (const t of toks) tf.set(t, (tf.get(t) || 0) + 1);
    chunkRows.push([chunkId, q(m.id), c.page, q(c.heading ?? null), q(c.text), toks.length]);
    for (const [t, n] of tf) termRows.push([q(t), q(m.id), chunkId, n, toks.length]);
    bump(m.id, tf.keys(), toks.length); bump("*", tf.keys(), toks.length);
  }
});
insert("manuals", "id, ord, corpus, title, maker, equipment, trust, source, pages, total_pages, pdf, figs, examples, parser, security, added_at", manualRows);
insert("pages", "manual_id, page, text", pageRows);
insert("chunks", "id, manual_id, page, heading, text, len", chunkRows);
insert("chunk_terms", "term, manual_id, chunk_id, tf, len", termRows);
const dfRows = []; for (const [scope, df] of scopeDf) for (const [t, n] of df) dfRows.push([q(scope), q(t), n]);
insert("scope_df", "scope, term, df", dfRows);
insert("scopes", "scope, n, total_len", [...scopes].map(([s, v]) => [q(s), v.n, v.total]));
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`${out}: ${data.manuals.length} manuals, ${pageRows.length} pages, ${chunkRows.length} passages, ${termRows.length} term rows, ${dfRows.length} df rows, ${(fs.statSync(out).size / 1e6).toFixed(1)} MB`);
