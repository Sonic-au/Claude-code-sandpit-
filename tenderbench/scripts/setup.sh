#!/usr/bin/env bash
# One-time setup for TenderBench in a fresh container (idempotent).
# Installs: Python venv with CPU PyTorch + Docling + scoring libs + anthropic SDK; MinerU in its own venv;
# LiteParse (npm) with local Tesseract English data. Needs network access to PyPI, download.pytorch.org,
# download-r2.pytorch.org, huggingface.co, us.aws.cdn.hf.co and the npm registry.
set -euo pipefail
cd "$(dirname "$0")/.."
TB=$PWD
VENV=${TB_VENV:-$TB/.venv}
MINERU_VENV=${TB_MINERU_VENV:-$TB/.venv-mineru}
NODE_DIR=${TB_NODE_DIR:-$TB/.node}

if [ ! -x "$VENV/bin/python" ]; then python3 -m venv "$VENV"; fi
"$VENV/bin/pip" install -q --upgrade pip
"$VENV/bin/pip" install -q torch torchvision --index-url https://download.pytorch.org/whl/cpu
"$VENV/bin/pip" install -q -r requirements.txt

if [ ! -x "$MINERU_VENV/bin/mineru-kit" ]; then
  python3 -m venv "$MINERU_VENV"
  "$MINERU_VENV/bin/pip" install -q --upgrade pip
  "$MINERU_VENV/bin/pip" install -q torch torchvision --index-url https://download.pytorch.org/whl/cpu
  "$MINERU_VENV/bin/pip" install -q -U "mineru[core]"
fi

mkdir -p "$NODE_DIR"
if [ ! -x "$NODE_DIR/node_modules/.bin/lit" ]; then
  (cd "$NODE_DIR" && [ -f package.json ] || npm init -y >/dev/null)
  (cd "$NODE_DIR" && npm install --silent @llamaindex/liteparse@2.18.0 @tesseract.js-data/eng@1.0.0)
fi
mkdir -p "$NODE_DIR/tessdata"
if [ ! -s "$NODE_DIR/tessdata/eng.traineddata" ]; then
  gunzip -c "$NODE_DIR/node_modules/@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz" > "$NODE_DIR/tessdata/eng.traineddata"
fi
echo "{\"tessdataPath\": \"$NODE_DIR/tessdata\"}" > "$NODE_DIR/liteparse.config.json"

cat > "$TB/scripts/env.sh" <<EOF
# Generated by scripts/setup.sh - source it before running the bench.
export HF_HUB_DISABLE_XET=1
export LITEPARSE_BIN=$NODE_DIR/node_modules/.bin/lit
export LITEPARSE_CONFIG=$NODE_DIR/liteparse.config.json
export MINERU_BIN=$MINERU_VENV/bin/mineru-kit
export MINERU_MODEL_SOURCE=huggingface
. $VENV/bin/activate
EOF
echo "Setup done. Next: . scripts/env.sh && scripts/run_all.sh"
